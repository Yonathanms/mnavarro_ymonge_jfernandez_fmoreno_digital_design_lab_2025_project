def line_to_byte(bits: str) -> int:
    bits = bits.strip().replace("#", "1").replace(".", "0")
    width = len(bits)
    if width > 8:
        raise ValueError(f"Línea demasiado ancha: {bits}")
    pad_left = (8 - width) // 2
    pad_right = 8 - width - pad_left
    padded = "0" * pad_left + bits + "0" * pad_right
    return int(padded, 2)


def resolve_pattern(char: str):
    pattern = BASE_GLYPHS.get(char)
    if pattern is None and char.upper() in BASE_GLYPHS:
        pattern = BASE_GLYPHS[char.upper()]
    return pattern


def glyph_rows(char: str):
    pattern = resolve_pattern(char)
    rows: list[int] = []
    if pattern is None:
        rows = [0] * GLYPH_ROWS
    else:
        for line in pattern:
            value = line_to_byte(line)
            rows.append(value)
            rows.append(value)
        while len(rows) < GLYPH_ROWS:
            rows.append(0)
        rows = rows[:GLYPH_ROWS]
    return rows


def main():
    all_rows: list[int] = []
    for code in range(256):
        char = chr(code)
        rows = glyph_rows(char)
        all_rows.extend(rows)

    OUTPUT_HEX.write_text("\n".join(f"{value:02X}" for value in all_rows) + "\n")

    mif_lines = [
        "WIDTH=8;",
        "DEPTH=4096;",
        "ADDRESS_RADIX=UNS;",
        "DATA_RADIX=HEX;",
        "",
        "CONTENT BEGIN",
    ]
    for addr, value in enumerate(all_rows):
        mif_lines.append(f"    {addr} : {value:02X};")
    mif_lines.append("END;")
    OUTPUT_MIF.write_text("\n".join(mif_lines) + "\n")

    print(f"Escribí {OUTPUT_HEX} y {OUTPUT_MIF} con {len(all_rows)} filas.")


if __name__ == "__main__":
    main()
